import { Either, Match, Option, pipe, String } from 'effect'
import { html, plainText, rawHtml } from '../../../html.ts'
import { languageAttributesFor } from '../../../Locales.ts'
import { translate, type SupportedLocale } from '../../../locales/index.ts'
import * as Routes from '../../../routes.ts'
import { errorPrefix, errorSummary, saveAndContinueButton } from '../../../shared-translation-elements.ts'
import * as StatusCodes from '../../../StatusCodes.ts'
import type { Uuid } from '../../../types/index.ts'
import { StreamlinePageResponse } from '../../Response/index.ts'
import type * as UseOfAiForm from './UseOfAiForm.ts'

export const UseOfAiPage = ({
  datasetReviewId,
  form,
  locale,
  otherAuthors,
}: {
  datasetReviewId: Uuid.Uuid
  form: UseOfAiForm.UseOfAiForm
  locale: SupportedLocale
  otherAuthors: boolean
}) => {
  const hasAnError = form._tag === 'InvalidForm'
  const t = translate(locale, 'review-a-dataset-flow')

  return StreamlinePageResponse({
    status: hasAnError ? StatusCodes.BadRequest : StatusCodes.OK,
    title: pipe('Use of Artificial Intelligence (AI)', errorPrefix(locale, hasAnError), plainText),
    nav: html`
      <a
        href="${(otherAuthors
          ? Routes.ReviewADatasetCheckInvitationsToAppear
          : Routes.ReviewADatasetOthersNeedToBeListedOnTheReview
        ).href({ datasetReviewId })}"
        class="back"
        >${t('forms', 'backLink')()}</a
      >
    `,
    main: html`
      <form method="post" action="${Routes.ReviewADatasetUseOfAi.href({ datasetReviewId })}" novalidate>
        ${hasAnError ? pipe(form, toErrorItems(otherAuthors), errorSummary(locale)) : ''}

        <h1><span ${languageAttributesFor('en')}>Use of Artificial Intelligence (AI)</span></h1>

        <p>
          <span ${languageAttributesFor('en')}
            >We ask all reviewers to disclose the use of AI that helped them generate new ideas for their PREreview.
            Examples of generative AI tools are ChatGPT and Gemini.</span
          >
        </p>

        <p>
          <span ${languageAttributesFor('en')}
            >You don’t need to declare AI tools used purely for language editing or accessibility needs, as long as the
            ideas in your PREreview are your own.</span
          >
        </p>

        <p>
          <span ${languageAttributesFor('en')}
            >We ask this to help readers understand how the review was created: whether it is human feedback, machine
            feedback, or a mix of both. We may remove any review with ideas entirely generated by AI.</span
          >
        </p>

        <div ${rawHtml(form._tag === 'InvalidForm' && Either.isLeft(form.generativeAiIdeas) ? 'class="error"' : '')}>
          <conditional-inputs>
            <fieldset
              role="group"
              ${rawHtml(
                form._tag === 'InvalidForm' && Either.isLeft(form.generativeAiIdeas)
                  ? 'aria-invalid="true" aria-errormessage="generative-ai-ideas-error"'
                  : '',
              )}
            >
              <legend>
                <h2>
                  <span ${languageAttributesFor('en')}
                    >${
                      otherAuthors
                        ? 'Did you, or any of the other authors, use AI to generate ideas for this review?'
                        : 'Did you use AI to generate ideas for this review?'
                    }</span
                  >
                </h2>
              </legend>

              ${
                form._tag === 'InvalidForm' && Either.isLeft(form.generativeAiIdeas)
                  ? html`
                      <div class="error-message" id="generative-ai-ideas-error">
                        <span class="visually-hidden">${t('forms', 'errorPrefix')()}:</span>
                        ${Match.valueTags(form.generativeAiIdeas.left, {
                          Missing: () => missingMessage(otherAuthors),
                        })}
                      </div>
                    `
                  : ''
              }

              <ol>
                <li>
                  <label>
                    <input
                      name="generativeAiIdeas"
                      id="generative-ai-ideas-no"
                      type="radio"
                      value="no"
                      ${pipe(
                        Match.value(form),
                        Match.when({ _tag: 'CompletedForm', generativeAiIdeas: 'no' }, () => 'checked'),
                        Match.orElse(() => ''),
                      )}
                    />
                    ${t('no')()}
                  </label>
                </li>
                <li>
                  <label>
                    <input
                      name="generativeAiIdeas"
                      type="radio"
                      value="yes"
                      aria-controls="generative-ai-ideas-details-control"
                      ${pipe(
                        Match.value(form),
                        Match.when({ _tag: 'CompletedForm', generativeAiIdeas: 'yes' }, () => 'checked'),
                        Match.orElse(() => ''),
                      )}
                    />
                    ${t('yes')()}
                  </label>
                  <div class="conditional" id="generative-ai-ideas-details-control">
                    <div>
                      <label for="generative-ai-ideas-details" class="textarea"
                        ><span ${languageAttributesFor('en')}
                          >${otherAuthors ? 'How did you or the other authors use it?' : 'How did you use it?'}</span
                        >
                        ${t('forms', 'optionalSuffix')()}</label
                      >
                      <textarea
                        name="generativeAiIdeasDetails"
                        id="generative-ai-ideas-details"
                        placeholder=" "
                        dir="auto"
                        rows="5"
                      >
${Match.valueTags(form, {
  EmptyForm: () => '',
  InvalidForm: form => Option.getOrElse(form.generativeAiIdeasDetails, () => String.empty),
  CompletedForm: form => Option.getOrElse(form.generativeAiIdeasDetails, () => String.empty),
})}</textarea>
                    </div>
                  </div>
                </li>
              </ol>
            </fieldset>
          </conditional-inputs>
        </div>

        ${saveAndContinueButton(locale)}
      </form>
    `,
    canonical: Routes.ReviewADatasetUseOfAi.href({ datasetReviewId }),
    js: hasAnError ? ['conditional-inputs.js', 'error-summary.js'] : ['conditional-inputs.js'],
    skipToLabel: 'form',
  })
}

const toErrorItems = (otherAuthors: boolean) => (form: UseOfAiForm.InvalidForm) => html`
  ${
    Either.isLeft(form.generativeAiIdeas)
      ? html`
          <li>
            <a href="#generative-ai-ideas-no">
              ${Match.valueTags(form.generativeAiIdeas.left, {
                Missing: () => missingMessage(otherAuthors),
              })}
            </a>
          </li>
        `
      : ''
  }
`

const missingMessage = (otherAuthors: boolean) =>
  html`<span ${languageAttributesFor('en')}
    >${
      otherAuthors
        ? 'Select yes if you, or any of the other authors, used AI to generate ideas for this review'
        : 'Select yes if you used AI to generate ideas for this review'
    }</span
  >`
